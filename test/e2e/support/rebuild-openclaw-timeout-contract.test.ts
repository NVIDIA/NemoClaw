import { describe, expect, it } from "vitest";

import {
  REBUILD_OPENCLAW_CONVERGENCE_COUNT,
  REBUILD_OPENCLAW_CONVERGENCE_TIMEOUT_MS,
  REBUILD_OPENCLAW_DOCKER_OUTAGE_PROOF_BUDGET_MS,
  REBUILD_OPENCLAW_INSTALL_TIMEOUT_MS,
  REBUILD_OPENCLAW_KILL_TIMEOUT_MS,
  REBUILD_OPENCLAW_NATIVE_READINESS_COUNT,
  REBUILD_OPENCLAW_NATIVE_READINESS_TIMEOUT_MS,
  REBUILD_OPENCLAW_POST_TEST_CLEANUP_BUDGET_MS,
  REBUILD_OPENCLAW_PRE_CLEANUP_TIMEOUT_MS,
  REBUILD_OPENCLAW_PRE_TEST_SETUP_BUDGET_MS,
  REBUILD_OPENCLAW_REBUILD_COUNT,
  REBUILD_OPENCLAW_REBUILD_TIMEOUT_MS,
  REBUILD_OPENCLAW_REQUIRED_OPERATION_BUDGET_MS,
  REBUILD_OPENCLAW_SOURCE_PROOF_BUDGET_MS,
  REBUILD_OPENCLAW_STOP_TIMEOUT_MS,
  REBUILD_OPENCLAW_TARGET_TIMEOUT_MINUTES,
  REBUILD_OPENCLAW_TEST_HEADROOM_MS,
  REBUILD_OPENCLAW_TEST_TIMEOUT_MS,
  REBUILD_OPENCLAW_WORKFLOW_FINALIZATION_BUDGET_MS,
} from "../../../tools/e2e/rebuild-openclaw-timeout-contract.mts";
import { FULL_E2E_STANDARD_PROFILE_PRE_TEST_MINUTES } from "../../../tools/e2e/full-e2e-timeout-contract.mts";
import {
  catalogueTarget,
  catalogueTargetsForChangedFiles,
} from "../../../tools/e2e/target-catalogue.mts";
import { DEFAULT_CLEANUP_TIMEOUT_MS } from "../fixtures/cleanup.ts";

const MINUTE_MS = 60_000;

describe("rebuild-openclaw timeout contract", () => {
  it("covers each bounded install, rebuild, convergence, and readiness operation", () => {
    expect(REBUILD_OPENCLAW_INSTALL_TIMEOUT_MS).toBe(20 * MINUTE_MS);
    expect(REBUILD_OPENCLAW_REBUILD_COUNT).toBe(3);
    expect(REBUILD_OPENCLAW_REBUILD_TIMEOUT_MS).toBe(20 * MINUTE_MS);
    expect(REBUILD_OPENCLAW_CONVERGENCE_COUNT).toBe(2);
    expect(REBUILD_OPENCLAW_CONVERGENCE_TIMEOUT_MS).toBe(MINUTE_MS);
    expect(REBUILD_OPENCLAW_NATIVE_READINESS_COUNT).toBe(3);
    expect(REBUILD_OPENCLAW_NATIVE_READINESS_TIMEOUT_MS).toBe(3 * MINUTE_MS);
    expect(REBUILD_OPENCLAW_PRE_CLEANUP_TIMEOUT_MS).toBe(2 * MINUTE_MS);
    expect(REBUILD_OPENCLAW_STOP_TIMEOUT_MS).toBe(2 * MINUTE_MS);
    expect(REBUILD_OPENCLAW_KILL_TIMEOUT_MS).toBe(30_000);
    expect(REBUILD_OPENCLAW_DOCKER_OUTAGE_PROOF_BUDGET_MS).toBe(4.5 * MINUTE_MS);
    expect(REBUILD_OPENCLAW_REQUIRED_OPERATION_BUDGET_MS).toBe(
      REBUILD_OPENCLAW_PRE_CLEANUP_TIMEOUT_MS +
        REBUILD_OPENCLAW_INSTALL_TIMEOUT_MS +
        REBUILD_OPENCLAW_REBUILD_COUNT * REBUILD_OPENCLAW_REBUILD_TIMEOUT_MS +
        REBUILD_OPENCLAW_CONVERGENCE_COUNT * REBUILD_OPENCLAW_CONVERGENCE_TIMEOUT_MS +
        REBUILD_OPENCLAW_NATIVE_READINESS_COUNT * REBUILD_OPENCLAW_NATIVE_READINESS_TIMEOUT_MS +
        REBUILD_OPENCLAW_STOP_TIMEOUT_MS +
        REBUILD_OPENCLAW_KILL_TIMEOUT_MS +
        REBUILD_OPENCLAW_DOCKER_OUTAGE_PROOF_BUDGET_MS,
    );
    expect(REBUILD_OPENCLAW_TEST_TIMEOUT_MS).toBeGreaterThanOrEqual(
      REBUILD_OPENCLAW_REQUIRED_OPERATION_BUDGET_MS +
        REBUILD_OPENCLAW_SOURCE_PROOF_BUDGET_MS +
        REBUILD_OPENCLAW_TEST_HEADROOM_MS,
    );
  });

  it("reserves setup, cleanup, and finalization outside the test timeout", () => {
    const targetTimeoutMinutes = catalogueTarget("rebuild-openclaw").timeoutMinutes;

    expect(REBUILD_OPENCLAW_PRE_TEST_SETUP_BUDGET_MS).toBeGreaterThanOrEqual(
      FULL_E2E_STANDARD_PROFILE_PRE_TEST_MINUTES * MINUTE_MS,
    );
    expect(REBUILD_OPENCLAW_POST_TEST_CLEANUP_BUDGET_MS).toBe(DEFAULT_CLEANUP_TIMEOUT_MS);
    expect(targetTimeoutMinutes).toBe(REBUILD_OPENCLAW_TARGET_TIMEOUT_MINUTES);
    expect(targetTimeoutMinutes * MINUTE_MS).toBe(
      REBUILD_OPENCLAW_PRE_TEST_SETUP_BUDGET_MS +
        REBUILD_OPENCLAW_TEST_TIMEOUT_MS +
        REBUILD_OPENCLAW_POST_TEST_CLEANUP_BUDGET_MS +
        REBUILD_OPENCLAW_WORKFLOW_FINALIZATION_BUDGET_MS,
    );
    expect(
      catalogueTargetsForChangedFiles(["tools/e2e/rebuild-openclaw-timeout-contract.mts"]).map(
        (target) => target.id,
      ),
    ).toContain("rebuild-openclaw");
  });
});
