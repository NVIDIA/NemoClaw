# Expand a two-sandbox pairing YAML to E2E_USERS sandboxes named user-0000
# … user-NNNN. Writes YAML to stdout. Does not apply.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
EXAMPLE_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"

PAIRING="${1:-}"
USERS="${2:-${E2E_USERS:-}}"

usage() {
  cat <<'EOF'
Usage: ./scripts/render-sandboxes.sh PAIRING [E2E_USERS]

PAIRING is one of: hermes-nim hermes-vllm deepagents-nim openclaw-ollama
E2E_USERS is an integer from 1 to 64. Default is the E2E_USERS env var.

The command prints a NemoClawConfig. It does not apply it.
Replace image digests and metadata.uid before apply.
EOF
}

if [[ "${PAIRING}" == "-h" || "${PAIRING}" == "--help" ]]; then
  usage
  exit 0
fi

case "${PAIRING}" in
  hermes-nim | hermes-vllm | deepagents-nim | openclaw-ollama) ;;
  *)
    usage >&2
    exit 2
    ;;
esac

if [[ -z "${USERS}" || ! "${USERS}" =~ ^[0-9]+$ ]] || ((USERS < 1 || USERS > 64)); then
  echo "E2E_USERS must be an integer from 1 to 64" >&2
  exit 2
fi

SOURCE_YAML="${EXAMPLE_DIR}/${PAIRING}.yaml"
if [[ ! -f "${SOURCE_YAML}" ]]; then
  echo "missing pairing file: ${SOURCE_YAML}" >&2
  exit 1
fi

python3 - "${SOURCE_YAML}" "${USERS}" <<'PY'
import copy
import sys
from pathlib import Path

import yaml

source = Path(sys.argv[1])
users = int(sys.argv[2])
doc = yaml.safe_load(source.read_text(encoding="utf-8"))
sandboxes = doc["spec"]["sandboxes"]
if not sandboxes:
    raise SystemExit(f"{source}: spec.sandboxes is empty")
template = next(iter(sandboxes.values()))
expanded = {}
for index in range(users):
    expanded[f"user-{index:04d}"] = copy.deepcopy(template)
doc["spec"]["sandboxes"] = expanded
sys.stdout.write(
    "# Generated by scripts/render-sandboxes.sh. Do not edit by hand.\n"
)
yaml.safe_dump(doc, sys.stdout, sort_keys=False)
PY
