# Print one NemoClawConfig with OpenClaw sandboxes and Hermes sandboxes.
# OpenClaw calls the Ollama release. Hermes calls the vLLM release.
# Does not apply.
#
#   ./scripts/render-mixed-sandboxes.sh > .local/openclaw-hermes.yaml
#
# Defaults: 2 OpenClaw sandboxes (user-0000, user-0001) and 6 Hermes
# sandboxes (user-0002 through user-0007). Image digests come from
# openclaw-ollama.yaml and hermes-vllm.yaml.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
EXAMPLE_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"

OPENCLAW_USERS="${OPENCLAW_USERS:-2}"
HERMES_USERS="${HERMES_USERS:-6}"
VLLM_RELEASE="${VLLM_RELEASE:-nemoclaw-gpu-vllm}"
OLLAMA_RELEASE="${OLLAMA_RELEASE:-nemoclaw-gpu-ollama}"

if [[ ! "${OPENCLAW_USERS}" =~ ^[0-9]+$ || ! "${HERMES_USERS}" =~ ^[0-9]+$ ]]; then
  echo "OPENCLAW_USERS and HERMES_USERS must be integers" >&2
  exit 2
fi
if ((OPENCLAW_USERS < 1 || HERMES_USERS < 1)); then
  echo "OPENCLAW_USERS and HERMES_USERS must be at least 1" >&2
  exit 2
fi
if ((OPENCLAW_USERS + HERMES_USERS > 32)); then
  echo "OPENCLAW_USERS + HERMES_USERS must be at most 32" >&2
  exit 2
fi

python3 - "${EXAMPLE_DIR}" "${OPENCLAW_USERS}" "${HERMES_USERS}" "${OLLAMA_RELEASE}" "${VLLM_RELEASE}" <<'PY'
import copy
import sys
from pathlib import Path

import yaml

example = Path(sys.argv[1])
openclaw_users = int(sys.argv[2])
hermes_users = int(sys.argv[3])
ollama_release = sys.argv[4]
vllm_release = sys.argv[5]

def load_pairing(name: str) -> dict:
    path = example / f"{name}.yaml"
    if not path.is_file():
        raise SystemExit(f"missing pairing file: {path}")
    return yaml.safe_load(path.read_text(encoding="utf-8"))

def first_sandbox(doc: dict, path_name: str) -> dict:
    sandboxes = doc["spec"]["sandboxes"]
    if not sandboxes:
        raise SystemExit(f"{path_name}: spec.sandboxes is empty")
    return next(iter(sandboxes.values()))

def service_url(release: str) -> str:
    return (
        f"http://{release}-metrics-proxy.{release}.svc.cluster.local:8081/v1"
    )

openclaw = load_pairing("openclaw-ollama")
hermes = load_pairing("hermes-vllm")
openclaw_template = first_sandbox(openclaw, "openclaw-ollama.yaml")
hermes_template = first_sandbox(hermes, "hermes-vllm.yaml")

doc = copy.deepcopy(openclaw)
doc["metadata"]["name"] = "gpu-autoscaling-openclaw-hermes"
doc["metadata"]["uid"] = "a7c3e1b2-4d58-4f0a-9c6e-2b8f0d1e6a44"
gateway = doc["spec"]["gateway"]
gateway["endpoint"] = "https://127.0.0.1:17673"
gateway["kubernetes"]["namespace"] = "nemoclaw-v1-gpu-autoscaling-mixed"

def provider(source_name: str, source: dict, endpoint: str, credential_env: str) -> dict:
    raw = source["spec"]["inferenceProviders"][source_name]
    return {
        "provider": raw["provider"],
        "api": raw["api"],
        "endpoint": endpoint,
        "credential": {"env": credential_env},
    }

doc["spec"]["inferenceProviders"] = {
    "gpu-ollama": provider(
        "gpu-ollama",
        openclaw,
        service_url(ollama_release),
        "GPU_OLLAMA_API_KEY",
    ),
    "gpu-vllm": provider(
        "gpu-vllm",
        hermes,
        service_url(vllm_release),
        "GPU_VLLM_API_KEY",
    ),
}

def place(template: dict, index: int, provider_ref: str, metadata_env: str) -> dict:
    sandbox = copy.deepcopy(template)
    sandbox["image"]["metadata"] = {"env": metadata_env}
    routes = sandbox["agent"]["inference"]["routes"]
    routes[0]["providerRef"] = provider_ref
    return sandbox

sandboxes = {}
for index in range(openclaw_users):
    sandboxes[f"user-{index:04d}"] = place(
        openclaw_template, index, "gpu-ollama", "NEMOCLAW_OPENCLAW_IMAGE_METADATA"
    )
for index in range(openclaw_users, openclaw_users + hermes_users):
    sandboxes[f"user-{index:04d}"] = place(
        hermes_template, index, "gpu-vllm", "NEMOCLAW_HERMES_IMAGE_METADATA"
    )
doc["spec"]["sandboxes"] = sandboxes

sys.stdout.write(
    "# Generated by scripts/render-mixed-sandboxes.sh. Do not edit by hand.\n"
)
yaml.safe_dump(doc, sys.stdout, sort_keys=False)
PY
