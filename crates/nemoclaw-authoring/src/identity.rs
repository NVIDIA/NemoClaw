use crate::{Diagnostics, diagnostics::diagnostic};

/// Generate a deployment identity without constructing a complete SDK document.
pub fn new_deployment_uid() -> Result<String, Diagnostics> {
    let mut bytes = [0_u8; 16];
    getrandom::fill(&mut bytes).map_err(|_| diagnostic("uid", "could not generate identity"))?;
    bytes[6] = (bytes[6] & 0x0f) | 0x40;
    bytes[8] = (bytes[8] & 0x3f) | 0x80;
    Ok(format!(
        "{:02x}{:02x}{:02x}{:02x}-{:02x}{:02x}-{:02x}{:02x}-{:02x}{:02x}-{:02x}{:02x}{:02x}{:02x}{:02x}{:02x}",
        bytes[0],
        bytes[1],
        bytes[2],
        bytes[3],
        bytes[4],
        bytes[5],
        bytes[6],
        bytes[7],
        bytes[8],
        bytes[9],
        bytes[10],
        bytes[11],
        bytes[12],
        bytes[13],
        bytes[14],
        bytes[15]
    ))
}
